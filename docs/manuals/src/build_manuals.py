def ex(cap, lines):
    return f'<div class="ex"><div class="cap">{escape(cap)}</div>' + "".join(f"<div>{escape(l)}</div>" for l in lines) + "</div>"


def box(kind, title, body):
    return f'<div class="box {kind}"><div class="bt">{title}</div>{body}</div>'


def table(head, rows):
    h = "".join(f"<th>{c}</th>" for c in head)
    b = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    return f"<table><thead><tr>{h}</tr></thead><tbody>{b}</tbody></table>"


def ul(items, tag="ul"):
    return f"<{tag}>" + "".join(f"<li>{i}</li>" for i in items) + f"</{tag}>"


def flow(steps):
    return '<div class="flow">' + "<span>→</span>".join(f"<div>{s}</div>" for s in steps) + "</div>"


